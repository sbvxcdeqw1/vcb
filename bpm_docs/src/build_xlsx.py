thin = Side(style="thin", color="C5CFDC"); BR = Border(left=thin, right=thin, top=thin, bottom=thin)
FILL = {"Пр": "E3F2EA", "З": "EFE6F8", "Н": "FDEEDB", "—": "EEF0F3"}

def sheet(ws, title, headers, rows, widths, srccol=None):
    ws.title = title
    ws.append(headers)
    for c in ws[1]:
        c.fill = HF; c.font = HFont; c.alignment = Alignment(wrap_text=True, vertical="center"); c.border = BR
    for r in rows: ws.append(r)
    for row in ws.iter_rows(min_row=2):
        for c in row:
            c.alignment = Alignment(wrap_text=True, vertical="top"); c.font = Font(name="Arial", size=10); c.border = BR
        if srccol is not None:
            v = row[srccol].value
            if v in FILL: row[srccol].fill = PatternFill("solid", fgColor=FILL[v])
    for i, w in enumerate(widths, 1): ws.column_dimensions[get_column_letter(i)].width = w
    ws.freeze_panes = "A2"; ws.auto_filter.ref = ws.dimensions
    ws.row_dimensions[1].height = 30

